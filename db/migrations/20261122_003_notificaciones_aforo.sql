CREATE TABLE IF NOT EXISTS preferencias_alerta_aforo (
  codigo_estudiante TEXT PRIMARY KEY
    REFERENCES estudiantes (codigo_estudiante) ON DELETE CASCADE,
  habilitada BOOLEAN NOT NULL DEFAULT FALSE,
  umbral INTEGER,
  dias SMALLINT[] NOT NULL DEFAULT ARRAY[]::SMALLINT[],
  hora_inicio SMALLINT NOT NULL DEFAULT 480,
  hora_fin SMALLINT NOT NULL DEFAULT 1080,
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT preferencias_alerta_umbral_check CHECK (umbral IS NULL OR umbral >= 1),
  CONSTRAINT preferencias_alerta_horas_check CHECK (
    hora_inicio BETWEEN 0 AND 1439 AND hora_fin BETWEEN 0 AND 1439
  ),
  CONSTRAINT preferencias_alerta_dias_check CHECK (
    array_position(dias, NULL) IS NULL
    AND dias <@ ARRAY[1, 2, 3, 4, 5, 6, 7]::SMALLINT[]
  ),
  CONSTRAINT preferencias_alerta_habilitada_check CHECK (
    NOT habilitada OR (umbral IS NOT NULL AND cardinality(dias) > 0 AND hora_inicio <> hora_fin)
  )
);

CREATE TABLE IF NOT EXISTS estado_alerta_aforo (
  codigo_estudiante TEXT PRIMARY KEY
    REFERENCES estudiantes (codigo_estudiante) ON DELETE CASCADE,
  en_periodo_bajo BOOLEAN NOT NULL DEFAULT FALSE,
  notificado BOOLEAN NOT NULL DEFAULT FALSE,
  episodio BIGINT NOT NULL DEFAULT 1 CHECK (episodio >= 1),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS notificaciones (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  codigo_estudiante TEXT NOT NULL
    REFERENCES estudiantes (codigo_estudiante) ON DELETE CASCADE,
  tipo TEXT NOT NULL,
  mensaje TEXT NOT NULL,
  episodio BIGINT,
  creada_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  leida_en TIMESTAMPTZ,
  CONSTRAINT notificaciones_tipo_check CHECK (
    tipo IN ('AFORO_BAJO', 'ADMINISTRATIVA', 'APERTURA', 'CIERRE', 'SISTEMA')
  )
);

CREATE UNIQUE INDEX IF NOT EXISTS notificaciones_aforo_episodio_uidx
  ON notificaciones (codigo_estudiante, tipo, episodio)
  WHERE tipo = 'AFORO_BAJO';

CREATE INDEX IF NOT EXISTS notificaciones_estudiante_recientes_idx
  ON notificaciones (codigo_estudiante, creada_en DESC, id DESC);

ALTER TABLE preferencias_alerta_aforo ENABLE ROW LEVEL SECURITY;
ALTER TABLE estado_alerta_aforo ENABLE ROW LEVEL SECURITY;
ALTER TABLE notificaciones ENABLE ROW LEVEL SECURITY;

REVOKE ALL PRIVILEGES ON TABLE
  preferencias_alerta_aforo,
  estado_alerta_aforo,
  notificaciones
FROM PUBLIC;
